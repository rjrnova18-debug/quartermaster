-- Postgres lets PUBLIC execute every new function; take that back and grant explicitly.
revoke execute on all functions in schema private from public, anon, authenticated;
grant execute on function private.my_role(), private.can_read_inspection(uuid),
  private.can_edit_inspection(uuid), private.file_inspection_id(text),
  private.can_write_file(text) to authenticated;   -- used inside policies

revoke execute on function public.save_inspection(jsonb), public.delete_inspection(uuid),
  public.save_attachment(jsonb), public.delete_attachment(uuid),
  public.set_user_role(uuid, text), public.changes_since(timestamptz)
  from public, anon;
grant execute on function public.save_inspection(jsonb), public.delete_inspection(uuid),
  public.save_attachment(jsonb), public.delete_attachment(uuid),
  public.set_user_role(uuid, text), public.changes_since(timestamptz)
  to authenticated;

