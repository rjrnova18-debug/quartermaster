-- Saves an inspection and its answers in one transaction (DATA-MODEL.md).
-- payload: { id, status, current_step, catalog_version, answers: { CODE: { value, note } } }
create function public.save_inspection(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid      uuid := auth.uid();
  v_role     text := private.my_role();
  v_id       uuid;
  v_step     int;
  v_version  int;
  v_status   text := payload ->> 'status';
  v_answers  jsonb := coalesce(payload -> 'answers', '{}'::jsonb);
  v_existing public.inspections%rowtype;
  v_result   public.inspections%rowtype;
  v_question public.questions%rowtype;
  v_groups   text[];
  v_code     text;
  v_answer   jsonb;
  v_value    text;
  v_note     text;
  v_summary  jsonb;
begin
  if v_uid is null or v_role is null then
    raise exception 'not_allowed';
  end if;

  -- Shape of the payload.
  begin
    v_id      := (payload ->> 'id')::uuid;
    v_step    := coalesce((payload ->> 'current_step')::int, 1);
    v_version := (payload ->> 'catalog_version')::int;
  exception when others then
    raise exception 'invalid: id, current_step or catalog_version';
  end;
  if v_id is null then
    raise exception 'invalid: id';
  end if;
  if v_status is null or v_status not in ('draft', 'completed') then
    raise exception 'invalid: status';
  end if;
  if jsonb_typeof(v_answers) <> 'object' then
    raise exception 'invalid: answers';
  end if;
  if not exists (select 1 from public.catalog_versions where version = v_version) then
    raise exception 'invalid: catalog_version';
  end if;

  -- Permission (ACCESS.md): a new id may be created by anyone signed in; an existing
  -- inspection only by whoever may edit it.
  select * into v_existing from public.inspections where id = v_id for update;
  if found then
    if not private.can_edit_inspection(v_id) then
      raise exception 'not_allowed';
    end if;
    if v_existing.status = 'completed' and v_status = 'draft' then
      raise exception 'invalid: a completed inspection stays completed';
    end if;
  end if;

  -- F1: the groups switched on by the chosen unit type.
  select ut.groups into v_groups
  from public.questions q
  join public.unit_types ut on ut.code = btrim(v_answers -> q.code ->> 'value')
  where q.kind = 'unit_type';
  v_groups := coalesce(v_groups, '{}');

  -- Integrity, always (a draft may be incomplete, never nonsense).
  for v_code, v_answer in select key, value from jsonb_each(v_answers) loop
    select * into v_question from public.questions where code = v_code;
    if not found or v_question.kind = 'heading' then
      raise exception 'invalid: unknown question %', left(v_code, 40);
    end if;
    if jsonb_typeof(v_answer) <> 'object' then
      raise exception 'invalid: answer %', v_code;
    end if;
    v_value := btrim(coalesce(v_answer ->> 'value', ''));
    v_note  := btrim(coalesce(v_answer ->> 'note', ''));
    if char_length(v_value) > 2000 or char_length(v_note) > 2000 then
      raise exception 'invalid: answer too long %', v_code;
    end if;
    continue when v_value = '';
    if v_question.kind = 'check' and v_value not in ('PASS', 'FAIL', 'NA') then
      raise exception 'invalid: check value %', v_code;
    elsif v_question.kind = 'choice' and not exists (
        select 1 from jsonb_array_elements(v_question.options) o where o ->> 'value' = v_value) then
      raise exception 'invalid: choice value %', v_code;
    elsif v_question.kind = 'unit_type' and not exists (
        select 1 from public.unit_types where code = v_value) then
      raise exception 'invalid: unit type %', v_code;
    elsif v_question.kind = 'date' and not private.is_iso_date(v_value) then
      raise exception 'invalid: date %', v_code;
    end if;
  end loop;

  -- F9 blocking rules, only when completing (F11).
  if v_status = 'completed' then
    for v_question in
      select * from public.questions q
      where q.kind <> 'heading' and (q.group_name is null or q.group_name = any (v_groups))
      order by q.position
    loop
      v_value := btrim(coalesce(v_answers -> v_question.code ->> 'value', ''));
      v_note  := btrim(coalesce(v_answers -> v_question.code ->> 'note', ''));
      if v_value = '' then
        if v_question.requirement = 'required' then
          raise exception 'invalid: required %', v_question.code;
        end if;
      elsif v_question.kind = 'check' and v_value = 'FAIL' and v_note = '' then
        raise exception 'invalid: note_needed %', v_question.code;
      elsif v_question.kind = 'digits' and v_value !~ '^[0-9]+$' then
        raise exception 'invalid: digits_only %', v_question.code;
      elsif v_question.kind = 'number' and v_value !~ '^[0-9]+(\.[0-9]+)?$' then
        raise exception 'invalid: not_a_number %', v_question.code;
      end if;
    end loop;
  end if;

  -- F18 computed HERE from the answers, never taken from the phone (B1).
  select jsonb_object_agg(s.field, nullif(btrim(coalesce(v_answers -> s.question_code ->> 'value', '')), ''))
    into v_summary
  from public.catalog_summary s;

  begin
    insert into public.inspections as i (
      id, status, current_step, catalog_version, created_by, inspector_name, completed_at,
      trip_ref, inspection_date, unit_type_code, truck_plate, container_no, driver_name, verdict)
    values (
      v_id, v_status, v_step, v_version, v_uid,
      coalesce((select full_name from public.profiles where id = v_uid), ''),
      case when v_status = 'completed' then now() end,
      v_summary ->> 'tripRef', (v_summary ->> 'inspectionDate')::date, v_summary ->> 'unitType',
      v_summary ->> 'truckPlate', v_summary ->> 'containerNo', v_summary ->> 'driverName',
      v_summary ->> 'verdict')
    on conflict (id) do update set
      status          = excluded.status,
      current_step    = excluded.current_step,
      catalog_version = excluded.catalog_version,
      completed_at    = coalesce(i.completed_at, excluded.completed_at),
      updated_at      = now(),
      trip_ref        = excluded.trip_ref,
      inspection_date = excluded.inspection_date,
      unit_type_code  = excluded.unit_type_code,
      truck_plate     = excluded.truck_plate,
      container_no    = excluded.container_no,
      driver_name     = excluded.driver_name,
      verdict         = excluded.verdict
    returning * into v_result;
  exception
    when unique_violation then
      raise exception 'duplicate_trip_ref';
    when check_violation then
      raise exception 'invalid: a summary answer is too long';
  end;

  -- One row per answer; blank answers are not stored.
  delete from public.answers where inspection_id = v_id;
  insert into public.answers (inspection_id, question_code, value, note)
  select v_id, a.key, btrim(a.value ->> 'value'), nullif(btrim(coalesce(a.value ->> 'note', '')), '')
  from jsonb_each(v_answers) a
  where btrim(coalesce(a.value ->> 'value', '')) <> '';

  return jsonb_build_object(
    'id', v_result.id,
    'status', v_result.status,
    'updated_at', v_result.updated_at,
    'completed_at', v_result.completed_at);
end;
$$;

-- Soft delete (DATA-MODEL.md). An inspector deletes only their own drafts; a supervisor
-- any inspection. Deleting what does not exist, or is already deleted, succeeds quietly.
-- Files are removed by the app through the Storage API (phase F3e).
create function public.delete_inspection(p_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v public.inspections%rowtype;
begin
  if auth.uid() is null or private.my_role() is null then
    raise exception 'not_allowed';
  end if;
  select * into v from public.inspections where id = p_id for update;
  if not found or v.deleted_at is not null then
    return jsonb_build_object('id', p_id, 'deleted', true);
  end if;
  if not (private.my_role() = 'supervisor'
          or (v.created_by = auth.uid() and v.status = 'draft')) then
    raise exception 'not_allowed';
  end if;
  update public.inspections set deleted_at = now(), updated_at = now() where id = p_id;
  return jsonb_build_object('id', p_id, 'deleted', true);
end;
$$;

-- Registers a file already uploaded to storage. row: { id, inspection_id, kind,
-- question_code, storage_path }. A report replaces the previous one and sets
-- report_generated_at without touching updated_at (rule R7).
create function public.save_attachment(attachment jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id      uuid;
  v_insp    uuid;
  v_kind    text := attachment ->> 'kind';
  v_code    text := nullif(attachment ->> 'question_code', '');
  v_path    text := attachment ->> 'storage_path';
  v_q_kind  text;
begin
  if auth.uid() is null or private.my_role() is null then
    raise exception 'not_allowed';
  end if;
  begin
    v_id   := (attachment ->> 'id')::uuid;
    v_insp := (attachment ->> 'inspection_id')::uuid;
  exception when others then
    raise exception 'invalid: id or inspection_id';
  end;
  if v_id is null or v_insp is null or v_path is null then
    raise exception 'invalid: id, inspection_id or storage_path';
  end if;
  if not private.can_write_file(v_path) or private.file_inspection_id(v_path) is distinct from v_insp then
    raise exception 'not_allowed';
  end if;

  if v_kind = 'report' then
    if v_code is not null or v_path <> v_insp::text || '/report.pdf' then
      raise exception 'invalid: report path';
    end if;
    delete from public.attachments where inspection_id = v_insp and kind = 'report' and id <> v_id;
    update public.inspections set report_generated_at = now() where id = v_insp;
  elsif v_kind in ('photo', 'signature') then
    select kind into v_q_kind from public.questions where code = v_code;
    if v_q_kind is distinct from v_kind then
      raise exception 'invalid: question_code';
    end if;
    if v_path !~ ('^' || v_insp::text || '/' || v_id::text || '\.(jpg|png)$') then
      raise exception 'invalid: storage_path';
    end if;
  else
    raise exception 'invalid: kind';
  end if;

  insert into public.attachments as t (id, inspection_id, kind, question_code, storage_path, created_by)
  values (v_id, v_insp, v_kind, v_code, v_path, auth.uid())
  on conflict (id) do update set storage_path = excluded.storage_path
    where t.inspection_id = excluded.inspection_id;
  return jsonb_build_object('id', v_id);
end;
$$;

-- Removes the record of a photo or signature (a replaced photo, S2). The file itself
-- is removed by the app through the Storage API.
create function public.delete_attachment(p_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v public.attachments%rowtype;
begin
  if auth.uid() is null or private.my_role() is null then
    raise exception 'not_allowed';
  end if;
  select * into v from public.attachments where id = p_id;
  if not found then
    return jsonb_build_object('id', p_id, 'deleted', true);
  end if;
  if not private.can_write_file(v.storage_path) then
    raise exception 'not_allowed';
  end if;
  delete from public.attachments where id = p_id;
  return jsonb_build_object('id', p_id, 'deleted', true);
end;
$$;

-- A supervisor changes someone else's role. Nobody changes their own.
create function public.set_user_role(p_user uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if private.my_role() is distinct from 'supervisor' or p_user = auth.uid() then
    raise exception 'not_allowed';
  end if;
  if p_role not in ('inspector', 'supervisor') then
    raise exception 'invalid: role';
  end if;
  update public.profiles set role = p_role where id = p_user;
end;
$$;

-- What changed since a moment, for the pull of the sync cycle (OFFLINE-SYNC.md).
-- SECURITY INVOKER: it reads through the caller's own row-level security, so it can only
-- return what the caller may see. Deleted rows are included on purpose.
create function public.changes_since(p_since timestamptz default '-infinity')
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'server_time', now(),
    'inspections', coalesce((
      select jsonb_agg(to_jsonb(i) || jsonb_build_object(
        'answers', coalesce((
          select jsonb_object_agg(a.question_code,
                                  jsonb_strip_nulls(jsonb_build_object('value', a.value, 'note', a.note)))
          from public.answers a where a.inspection_id = i.id), '{}'::jsonb),
        'attachments', coalesce((
          select jsonb_agg(to_jsonb(t)) from public.attachments t where t.inspection_id = i.id), '[]'::jsonb)))
      from public.inspections i
      where i.updated_at > p_since or i.report_generated_at > p_since), '[]'::jsonb),
    'drivers',  coalesce((select jsonb_agg(to_jsonb(d)) from public.drivers d  where d.updated_at > p_since), '[]'::jsonb),
    'carriers', coalesce((select jsonb_agg(to_jsonb(c)) from public.carriers c where c.updated_at > p_since), '[]'::jsonb),
    'vehicles', coalesce((select jsonb_agg(to_jsonb(v)) from public.vehicles v where v.updated_at > p_since), '[]'::jsonb)
  );
$$;

