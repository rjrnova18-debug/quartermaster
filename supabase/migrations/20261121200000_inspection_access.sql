-- Quartermaster · inspection module · access (phase F2b)
--
-- Who may read and write what (docs: ACCESS.md). Design choices:
--
-- * Least privilege. Nothing was granted to the API roles in F2a; this file grants only
--   what each table needs, and only to `authenticated` (signed-in people). `anon` gets
--   nothing at all.
-- * One door for inspection data. Inspections, answers and attachments are never written
--   with plain INSERT/UPDATE from the app: the API roles may only SELECT them, and every
--   write goes through a function below that checks permissions and validates the data.
-- * The phone is not trusted. save_inspection() recomputes the summary from the answers
--   itself and re-checks the completion rules (decisions B1 and B2).
-- * Helpers live in the `private` schema, which the Data API does not expose, so they
--   cannot be called from outside. SECURITY DEFINER functions always fix search_path.
--
-- Errors the app understands (OFFLINE-SYNC.md S8): 'not_allowed', 'duplicate_trip_ref'
-- and 'invalid: <detail>'.

-- ---------------------------------------------------------------- private helpers

create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated, service_role;

-- The role of the caller ('inspector' or 'supervisor'), or null when not signed in.
-- SECURITY DEFINER so the policies on `profiles` do not call themselves.
create function private.my_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.profiles where id = auth.uid();
$$;

-- R/W rules for one inspection, shared by policies, functions and storage.
create function private.can_read_inspection(p_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.inspections i
    where i.id = p_id
      and (i.created_by = auth.uid() or private.my_role() = 'supervisor')
  );
$$;

-- F19 / ACCESS.md: supervisors may edit any live inspection; an inspector only their own,
-- while it is a draft or for 24 hours after completing it. Mirrors canEditInspection()
-- in src/inspection/form.ts.
create function private.can_edit_inspection(p_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.inspections i
    where i.id = p_id
      and i.deleted_at is null
      and (
        private.my_role() = 'supervisor'
        or (i.created_by = auth.uid()
            and (i.status = 'draft' or i.completed_at > now() - interval '24 hours'))
      )
  );
$$;

-- The inspection id that is the first folder of a storage path, or null.
create function private.file_inspection_id(p_name text)
returns uuid
language sql
immutable
set search_path = ''
as $$
  select case
    when split_part(p_name, '/', 1) ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    then split_part(p_name, '/', 1)::uuid
  end;
$$;

-- Who may upload, replace or remove a file of an inspection. The report of a completed
-- inspection may be (re)generated by anyone who can read it, even after the 24 hours.
create function private.can_write_file(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when split_part(p_name, '/', 2) = 'report.pdf' then
      private.can_read_inspection(private.file_inspection_id(p_name))
      and exists (select 1 from public.inspections i
                  where i.id = private.file_inspection_id(p_name)
                    and i.status = 'completed' and i.deleted_at is null)
    else private.can_edit_inspection(private.file_inspection_id(p_name))
  end;
$$;

-- True for a real calendar date written as YYYY-MM-DD.
create function private.is_iso_date(p_text text)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
begin
  if p_text !~ '^\d{4}-\d{2}-\d{2}$' then
    return false;
  end if;
  return to_char(p_text::date, 'YYYY-MM-DD') = p_text;
exception when others then
  return false;
end;
$$;

-- New sign-ups get a profile with the inspector role. The role is never taken from the
-- sign-up metadata: a user can write anything there.
create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, left(coalesce(new.raw_user_meta_data ->> 'full_name', ''), 120));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- The server sets updated_at; a client cannot backdate or forward-date a record.
create function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

