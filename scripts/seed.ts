/**
 * Loads the invented demo data (src/demo/demo-data.ts) into the Supabase dev project.
 *
 *   npm run seed
 *
 * Needs the three Supabase values in .env. DEMO_PASSWORD (optional) is the password of
 * the three demo accounts; without it they get a random one that nobody knows.
 *
 * Repeatable: it first removes what an earlier run created (same ids), then creates it
 * again. Inspections are saved through save_inspection while signed in as their owner,
 * so the server validates them and computes their summary exactly as for the app.
 */
import { randomUUID } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { parseEnv } from 'node:util';

import { createClient, SupabaseClient } from '@supabase/supabase-js';

import { buildDemoData, DemoInspection, DemoPerson, demoId } from '../src/demo/demo-data';
import { displayCode } from '../src/inspection/review';

const ROOT = path.join(__dirname, '..');
const BUCKET = 'inspection-files';
const noSession = { auth: { persistSession: false, autoRefreshToken: false } };

// ---------------------------------------------------------------- setup

function loadEnv(): Record<string, string | undefined> {
  const file = path.join(ROOT, '.env');
  const env = existsSync(file) ? { ...parseEnv(readFileSync(file, 'utf8')), ...process.env } : process.env;
  for (const name of ['EXPO_PUBLIC_SUPABASE_URL', 'EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY', 'SUPABASE_SECRET_KEY']) {
    if (!env[name]) {
      throw new Error(`Missing ${name} in .env (see .env.example)`);
    }
  }
  return env;
}

/** What every supabase-js call returns: the data, or an error and no data. */
type Result<T> = { data: T; error: null } | { data: unknown; error: { message: string } };

/** Returns the data, or stops the seed with a readable message when the call failed. */
function must<T>(step: string, result: Result<T>): T {
  if (result.error) {
    throw new Error(`${step}: ${result.error.message}`);
  }
  return result.data as T;
}

/** YYYY-MM-DD of this computer's calendar day. */
function localDate(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
}

/** A one-page PDF that stands in for the report the app generates on the phone. */
function placeholderReport(inspection: DemoInspection): Buffer {
  const lines = [
    'Quartermaster - demo report placeholder',
    `Inspection ${displayCode(inspection.id)} / trip ${inspection.answers.TRIP_REF?.value ?? '-'}`,
    'The real report is generated by the app on the phone.',
    'Everything in this demo is invented.',
  ];
  const content = lines.map((line, i) => `BT /F1 14 Tf 60 ${770 - i * 24} Td (${line}) Tj ET`).join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = objects.map((object, i) => {
    const offset = pdf.length;
    pdf += `${i + 1} 0 obj\n${object}\nendobj\n`;
    return offset;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`).join('');
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

// ---------------------------------------------------------------- steps

/** Creates the account, or updates it if it exists, and sets the role in its profile. */
async function upsertPerson(admin: SupabaseClient, person: DemoPerson, password: string): Promise<string> {
  const { users } = must('list users', await admin.auth.admin.listUsers({ perPage: 1000 }));
  const existing = users.find((user) => user.email === person.email);
  const attributes = { email: person.email, password, email_confirm: true, user_metadata: { full_name: person.fullName } };
  const { user } = existing
    ? must(`update ${person.email}`, await admin.auth.admin.updateUserById(existing.id, attributes))
    : must(`create ${person.email}`, await admin.auth.admin.createUser(attributes));
  must(
    `profile of ${person.email}`,
    await admin.from('profiles').update({ full_name: person.fullName, role: person.role }).eq('id', user.id),
  );
  return user.id;
}

/** Removes what an earlier run left: files first, then rows (answers and attachments cascade). */
async function removePrevious(admin: SupabaseClient, data: ReturnType<typeof buildDemoData>) {
  for (const inspection of data.inspections) {
    const files = must('list files', await admin.storage.from(BUCKET).list(inspection.id)) ?? [];
    if (files.length > 0) {
      const paths = files.map((file) => `${inspection.id}/${file.name}`);
      must('remove files', await admin.storage.from(BUCKET).remove(paths));
    }
  }
  must('remove inspections', await admin.from('inspections').delete().in('id', data.inspections.map((i) => i.id)));
  for (const table of ['drivers', 'carriers', 'vehicles'] as const) {
    must(`remove ${table}`, await admin.from(table).delete().in('id', data[table].map((row) => row.id)));
  }
}

async function insertDirectory(admin: SupabaseClient, data: ReturnType<typeof buildDemoData>, createdBy: string) {
  must('insert carriers', await admin.from('carriers').insert(
    data.carriers.map((c) => ({ id: c.id, name: c.name, contact_name: c.contactName, created_by: createdBy })),
  ));
  must('insert drivers', await admin.from('drivers').insert(
    data.drivers.map((d) => ({ id: d.id, name: d.name, id_number: d.idNumber, phone: d.phone, created_by: createdBy })),
  ));
  must('insert vehicles', await admin.from('vehicles').insert(
    data.vehicles.map((v) => ({ id: v.id, plate: v.plate, description: v.description, created_by: createdBy })),
  ));
}

/** Saves one inspection as its owner, uploads its files, then moves its dates into the past. */
async function loadInspection(
  admin: SupabaseClient,
  owner: SupabaseClient,
  data: ReturnType<typeof buildDemoData>,
  inspection: DemoInspection,
) {
  const label = displayCode(inspection.id);
  must(`save ${label}`, await owner.rpc('save_inspection', {
    payload: {
      id: inspection.id,
      status: inspection.status,
      current_step: inspection.currentStep,
      catalog_version: inspection.catalogVersion,
      answers: inspection.answers,
    },
  }));

  for (const attachment of data.attachments.filter((a) => a.inspectionId === inspection.id)) {
    const storagePath = `${inspection.id}/${attachment.id}.png`;
    const image = readFileSync(path.join(ROOT, 'assets', 'demo', attachment.asset));
    must(`upload ${attachment.asset}`, await owner.storage.from(BUCKET).upload(storagePath, image, { contentType: 'image/png' }));
    must(`register ${attachment.asset}`, await owner.rpc('save_attachment', {
      attachment: {
        id: attachment.id,
        inspection_id: inspection.id,
        kind: attachment.kind,
        question_code: attachment.questionCode,
        storage_path: storagePath,
      },
    }));
  }

  if (inspection.reportGeneratedAt !== null) {
    const reportPath = `${inspection.id}/report.pdf`;
    must(`upload report ${label}`, await owner.storage.from(BUCKET).upload(reportPath, placeholderReport(inspection), {
      contentType: 'application/pdf',
    }));
    must(`register report ${label}`, await owner.rpc('save_attachment', {
      attachment: { id: demoId(`${inspection.id}/report`), inspection_id: inspection.id, kind: 'report', storage_path: reportPath },
    }));
  }

  // The functions stamp everything with the server time; the demo needs the last ten days.
  must(`dates of ${label}`, await admin.from('inspections').update({
    created_at: inspection.createdAt,
    updated_at: inspection.updatedAt,
    completed_at: inspection.completedAt,
    report_generated_at: inspection.reportGeneratedAt,
  }).eq('id', inspection.id));
  must(`attachment dates of ${label}`, await admin.from('attachments')
    .update({ created_at: inspection.completedAt ?? inspection.updatedAt })
    .eq('inspection_id', inspection.id)
    .neq('kind', 'report'));
  if (inspection.reportGeneratedAt !== null) {
    must(`report date of ${label}`, await admin.from('attachments')
      .update({ created_at: inspection.reportGeneratedAt })
      .eq('inspection_id', inspection.id)
      .eq('kind', 'report'));
  }
}

// ---------------------------------------------------------------- main

async function main() {
  const env = loadEnv();
  const url = env.EXPO_PUBLIC_SUPABASE_URL!;
  const admin = createClient(url, env.SUPABASE_SECRET_KEY!, noSession);
  const password = env.DEMO_PASSWORD || randomUUID();
  const now = new Date();
  const data = buildDemoData(localDate(now), now.toISOString());

  console.log('Accounts...');
  const ids = new Map<string, string>();
  for (const person of data.people) {
    ids.set(person.key, await upsertPerson(admin, person, password));
  }

  console.log('Removing the previous demo...');
  await removePrevious(admin, data);

  console.log('Directory...');
  await insertDirectory(admin, data, ids.get('robin')!);

  console.log('Inspections...');
  for (const person of data.people) {
    const mine = data.inspections.filter((i) => i.owner === person.key);
    if (mine.length === 0) {
      continue;
    }
    const client = createClient(url, env.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, noSession);
    must(`sign in ${person.email}`, await client.auth.signInWithPassword({ email: person.email, password }));
    for (const inspection of mine) {
      await loadInspection(admin, client, data, inspection);
    }
    await client.auth.signOut();
  }

  console.log(
    `Done: ${data.inspections.length} inspections, ${data.attachments.length} photos and signatures, ` +
      `${data.carriers.length + data.drivers.length + data.vehicles.length} directory records.`,
  );
  console.log(`Accounts: ${data.people.map((p) => p.email).join(', ')}`);
  console.log(
    env.DEMO_PASSWORD
      ? 'Their password is DEMO_PASSWORD from .env.'
      : 'DEMO_PASSWORD is not set, so they got a random password nobody knows. Set it in .env and run again to sign in as them.',
  );
}

main().catch((error: Error) => {
  console.error(`Seed failed: ${error.message}`);
  process.exit(1);
});
