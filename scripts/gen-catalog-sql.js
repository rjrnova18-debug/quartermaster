/**
 * Turns catalog/questions.json into a SQL migration that loads the catalog into the
 * database (unit_types, questions, catalog_summary, catalog_versions).
 *
 *   npm run gen:catalog
 *
 * Each catalog version becomes its own migration file, so the database history in git
 * shows when the form changed. Re-running it for the same version rewrites the same file.
 * A test (tests/catalog-sql.test.ts) fails if the file is missing or out of date.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const MIGRATIONS = path.join(ROOT, 'supabase', 'migrations');

/** A SQL string literal: wrapped in single quotes, inner quotes doubled. */
function text(value) {
  if (value === null || value === undefined) {
    return 'null';
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Builds the migration for one catalog. Pure: same catalog in, same SQL out. */
function catalogSql(catalog) {
  const lines = [
    `-- Quartermaster · inspection catalog, version ${catalog.version}`,
    '-- GENERATED by scripts/gen-catalog-sql.js from catalog/questions.json. Do not edit by hand.',
    '',
    `insert into public.catalog_versions (version) values (${catalog.version})`,
    '  on conflict (version) do nothing;',
    '',
  ];

  catalog.unitTypes.forEach((unitType, position) => {
    const groups = `array[${unitType.groups.map(text).join(', ')}]::text[]`;
    lines.push(
      'insert into public.unit_types (code, label_en, label_es, groups, position) values',
      `  (${text(unitType.code)}, ${text(unitType.label.en)}, ${text(unitType.label.es)}, ${groups}, ${position + 1})`,
      '  on conflict (code) do update set label_en = excluded.label_en, label_es = excluded.label_es,',
      '    groups = excluded.groups, position = excluded.position;',
    );
  });
  lines.push('');

  catalog.questions.forEach((question, position) => {
    const options = question.options ? `${text(JSON.stringify(question.options))}::jsonb` : 'null';
    lines.push(
      'insert into public.questions (code, step, position, kind, requirement, group_name, label_en, label_es, options) values',
      `  (${text(question.code)}, ${question.step}, ${position + 1}, ${text(question.kind)}, ${text(question.requirement)},` +
        ` ${text(question.group)}, ${text(question.label.en)}, ${text(question.label.es)}, ${options})`,
      '  on conflict (code) do update set step = excluded.step, position = excluded.position, kind = excluded.kind,',
      '    requirement = excluded.requirement, group_name = excluded.group_name, label_en = excluded.label_en,',
      '    label_es = excluded.label_es, options = excluded.options;',
    );
  });
  lines.push('');

  for (const [field, code] of Object.entries(catalog.summary)) {
    lines.push(
      `insert into public.catalog_summary (field, question_code) values (${text(field)}, ${text(code)})`,
      '  on conflict (field) do update set question_code = excluded.question_code;',
    );
  }
  lines.push('');
  return lines.join('\n');
}

/** The file name for a catalog version; the timestamp keeps migrations in order. */
function migrationName(version) {
  return `20261121190100_catalog_v${version}.sql`;
}

/** Finds the existing migration of a version, whatever its timestamp. */
function findMigration(version) {
  const suffix = `_catalog_v${version}.sql`;
  const match = fs.readdirSync(MIGRATIONS).find((name) => name.endsWith(suffix));
  return match ? path.join(MIGRATIONS, match) : null;
}

function readCatalog() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'catalog', 'questions.json'), 'utf8'));
}

if (require.main === module) {
  const catalog = readCatalog();
  const file = findMigration(catalog.version) ?? path.join(MIGRATIONS, migrationName(catalog.version));
  fs.writeFileSync(file, catalogSql(catalog));
  console.log(`Wrote ${path.relative(ROOT, file)}`);
}

module.exports = { catalogSql, findMigration, readCatalog };
