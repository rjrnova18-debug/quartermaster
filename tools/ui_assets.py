"""Exports the pixel-art kit the app draws with.

    python tools/ui_assets.py

Writes assets/ui/*.png and src/ui/assets.generated.ts. The output is always the same.

How a frame reaches the screen (nine-slice): the four corners become small images; the
four edges and the middle are single colours, so the app draws them as plain views that
stretch to any size without blurring. One art pixel is 2 dp on screen (PIXEL in
src/ui/theme.ts), so images are written at 4x (@2x phones) and 6x (@3x phones).
"""
import os

from sprites32 import PAL, dawn_scene, frame, icon, node, png, truck

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT_PNG = os.path.join(ROOT, 'assets', 'ui')
OUT_TS = os.path.join(ROOT, 'src', 'ui', 'assets.generated.ts')
PIXEL_DP = 2
DENSITIES = {'@2x': 2, '@3x': 3}

R2 = [2, 1]  # corner profile of panels and buttons: 2 px then 1 px cut away

# name -> (drawing, corner profile, depth). Pressed buttons have no depth: they sank.
FRAMES = {
    'panel': (frame(10, R2, 'k', 'p', hi='w', lo='e'), R2, 0),
    'card': (frame(10, R2, 'k', 'w', lo='e'), R2, 0),
    'field': (frame(10, [1], 'k', 'w', hi='m'), [1], 0),
    'field-fail': (frame(10, [1], 'R', 'w', ring='q'), [1], 0),
    'btn-orange': (frame(10, R2, 'k', 'o', hi='h', lo='Q', depth=2, depth_c='O'), R2, 2),
    'btn-orange-pressed': (frame(10, R2, 'k', 'o', hi='h', lo='Q'), R2, 0),
    'btn-paper': (frame(10, R2, 'k', 'p', hi='w', lo='m', depth=2, depth_c='n'), R2, 2),
    'btn-paper-pressed': (frame(10, R2, 'k', 'p', hi='w', lo='m'), R2, 0),
    # the three check stamps: square, octagon, round (UI-BRIEF D3); "on" = chosen
    'stamp-pass-off': (frame(12, [1], 'G', 'w', ring='l'), [1], 0),
    'stamp-pass-on': (frame(12, [1], 'k', 'G', hi='g'), [1], 0),
    'stamp-fail-off': (frame(16, [4, 3, 2, 1], 'R', 'w', ring='q'), [4, 3, 2, 1], 0),
    'stamp-fail-on': (frame(16, [4, 3, 2, 1], 'k', 'R', hi='r'), [4, 3, 2, 1], 0),
    'stamp-na-off': (frame(18, [5, 3, 2, 1, 1], 'B', 'w', ring='c'), [5, 3, 2, 1, 1], 0),
    'stamp-na-on': (frame(18, [5, 3, 2, 1, 1], 'k', 'B', hi='v'), [5, 3, 2, 1, 1], 0),
    # choice buttons and unit-type cards when chosen
    'chosen': (frame(10, R2, 'k', 'h', hi='w', lo='o'), R2, 0),
}


def yard_scene():
    """The dawn yard with the dry truck parked in it (sign-in and home)."""
    g = dawn_scene()
    g.stamp(truck().rows(), 66, 27)
    return g


SPRITES = {
    'yard-scene': yard_scene(),
    'truck-dry': truck(),
    'truck-reefer': truck(reefer=True),
    'node-done': node('done'),
    'node-current': node('current'),
    'node-todo': node('todo'),
    'node-skip': node('skip'),
    'icon-check': icon('check'),
    'icon-cross': icon('cross'),
    'icon-dash': icon('dash'),
    'icon-snow': icon('snow'),
    'icon-alert': icon('alert'),
}


def colour(ch):
    return None if ch == '.' else PAL[ch]


def crop(rows, x0, y0, x1, y1):
    return [row[x0:x1] for row in rows[y0:y1]]


def write(rows, name):
    for suffix, density in DENSITIES.items():
        scale = PIXEL_DP * density
        scaled = [''.join(ch * scale for ch in row) for row in rows for _ in range(scale)]
        png(scaled, os.path.join(OUT_PNG, f'{name}{suffix}.png'))


def slice_frame(name, grid, profile, depth):
    """Corners as images; edges and fill as colours. Checks that the edges really are uniform."""
    rows = grid.rows()
    w, h = len(rows[0]), len(rows)
    side = len(profile) + 2          # cut-away corner + outline + bevel
    bottom = side + depth
    mid_x, mid_y = side, side

    for y in range(h):                # every middle column repeats the first one
        assert len({rows[y][x] for x in range(side, w - side)}) == 1, (name, 'column', y)
    for x in range(w):                # every middle row repeats the first one
        assert len({rows[y][x] for y in range(side, h - bottom)}) == 1, (name, 'row', x)

    for corner, (x0, y0) in {
        'tl': (0, 0), 'tr': (w - side, 0), 'bl': (0, h - bottom), 'br': (w - side, h - bottom),
    }.items():
        height = side if corner[0] == 't' else bottom
        write(crop(rows, x0, y0, x0 + side, y0 + height), f'frame-{name}-{corner}')

    return {
        'side': side,
        'bottom': bottom,
        'fill': colour(rows[mid_y][mid_x]),
        'top': [colour(rows[y][mid_x]) for y in range(0, side)],
        'bottomEdge': [colour(rows[y][mid_x]) for y in range(h - bottom, h)],
        'left': [colour(rows[mid_y][x]) for x in range(0, side)],
        'right': [colour(rows[mid_y][x]) for x in range(w - side, w)],
    }


def ts_list(colours):
    return '[' + ', '.join('null' if c is None else f"'{c}'" for c in colours) + ']'


def camel(name):
    head, *rest = name.split('-')
    return head + ''.join(part.capitalize() for part in rest)


def main():
    os.makedirs(OUT_PNG, exist_ok=True)
    lines = [
        '// Generated by tools/ui_assets.py. Do not edit: change the drawing and run it again.',
        "import { ImageSourcePropType } from 'react-native';",
        '',
        '/** A stretchable frame: sizes in art pixels; edge colours in screen order (null = transparent). */',
        'export interface FrameArt {',
        '  side: number;',
        '  bottom: number;',
        '  fill: string;',
        '  top: (string | null)[];',
        '  bottomEdge: (string | null)[];',
        '  left: (string | null)[];',
        '  right: (string | null)[];',
        '  corners: { tl: ImageSourcePropType; tr: ImageSourcePropType; bl: ImageSourcePropType; br: ImageSourcePropType };',
        '}',
        '',
        'export const FRAMES = {',
    ]
    for name, (grid, profile, depth) in FRAMES.items():
        art = slice_frame(name, grid, profile, depth)
        corners = ', '.join(f"{c}: require('../../assets/ui/frame-{name}-{c}.png')" for c in ('tl', 'tr', 'bl', 'br'))
        lines += [
            f'  {camel(name)}: {{',
            f"    side: {art['side']},",
            f"    bottom: {art['bottom']},",
            f"    fill: '{art['fill']}',",
            f"    top: {ts_list(art['top'])},",
            f"    bottomEdge: {ts_list(art['bottomEdge'])},",
            f"    left: {ts_list(art['left'])},",
            f"    right: {ts_list(art['right'])},",
            f'    corners: {{ {corners} }},',
            '  },',
        ]
    lines += ['} satisfies Record<string, FrameArt>;', '', 'export type FrameName = keyof typeof FRAMES;', '']
    lines += ['/** Whole images; width and height in art pixels. */', 'export const SPRITES = {']
    for name, grid in SPRITES.items():
        write(grid.rows(), name)
        lines.append(f"  {camel(name)}: {{ width: {grid.w}, height: {grid.h}, "
                     f"source: require('../../assets/ui/{name}.png') as ImageSourcePropType }},")
    lines += ['};', '']
    with open(OUT_TS, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'{len(FRAMES)} frames and {len(SPRITES)} sprites -> assets/ui, src/ui/assets.generated.ts')


if __name__ == '__main__':
    main()
